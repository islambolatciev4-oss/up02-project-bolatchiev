-- Пара 3, задание 3: пять запросов

-- Запрос 1. Все товары
SELECT * FROM Товар;

-- Запрос 2. Название и цена
SELECT название, цена FROM Товар;

-- Запрос 3. Товары дороже 5000
SELECT название, цена FROM Товар WHERE цена > 5000;

-- Запрос 4. Товары с количеством не больше 3
SELECT название, количество FROM Товар WHERE количество <= 3;

-- Запрос 5. Сортировка по цене (по возрастанию)
SELECT название, цена FROM Товар ORDER BY цена ASC;
